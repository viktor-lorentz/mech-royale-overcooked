//! Calibration against the recorded stream (kit/check/stream.jsonl.gz): `mech-sim --calibrate`.
use crate::cfg::Cfg;
use crate::combat::dist3;
use crate::map::World;
use crate::phys::wrap;
use crate::sim::*;
use mech_bot::protocol::*;
use std::collections::{HashMap, HashSet};
use std::io::Read;
use std::sync::Arc;

const STREAM: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/fixtures/stream.jsonl.gz");

struct Stat {
    name: &'static str,
    n: usize,
    sum: f64,
    max: f64,
    bad: usize,
    tol: f64,
}
impl Stat {
    fn new(name: &'static str, tol: f64) -> Stat {
        Stat { name, n: 0, sum: 0.0, max: 0.0, bad: 0, tol }
    }
    fn add(&mut self, e: f64) {
        let e = e.abs();
        self.n += 1;
        self.sum += e;
        if e > self.max {
            self.max = e;
        }
        if e > self.tol {
            self.bad += 1;
        }
    }
    fn line(&self) -> String {
        format!("| {} | {} | {:.4} | {:.4} | {} ({:.1}%) | {} |", self.name, self.n, self.sum / self.n.max(1) as f64, self.max, self.bad, 100.0 * self.bad as f64 / self.n.max(1) as f64, self.tol)
    }
}

fn hyp(a: f64, b: f64) -> f64 {
    (a * a + b * b).sqrt()
}

pub fn run(cfg: &Arc<Cfg>, world: &Arc<World>) {
    let mut txt = String::new();
    let f = std::fs::File::open(STREAM).expect("stream fixture");
    flate2::read::GzDecoder::new(f).read_to_string(&mut txt).expect("gunzip");
    let mut obs: Vec<Obs> = vec![];
    for l in txt.lines() {
        let v: serde_json::Value = match serde_json::from_str(l) {
            Ok(v) => v,
            Err(_) => continue,
        };
        if v["type"] == "obs" {
            if let Ok(o) = serde_json::from_value::<Obs>(v) {
                obs.push(o);
            }
        }
    }
    println!("# Calibration report (generated by `mech-sim --calibrate`)\n");
    println!("Recording: {} observations, ticks {}..{}.\n", obs.len(), obs[0].tick, obs.last().unwrap().tick);

    let mut sim = Sim::new(cfg.clone(), world.clone(), 1);

    // ---------------------------------------------------------------- A. kinematics
    let mut s_pos = Stat::new("position error (m)", 0.05);
    let mut s_posz = Stat::new("z error (m)", 0.05);
    let mut s_vel = Stat::new("velocity error (m/s)", 0.1);
    let mut s_velz = Stat::new("vz error (m/s)", 0.1);
    let mut s_en = Stat::new("energy error", 0.25);
    let mut s_gr = Stat::new("grounded flag mismatch", 0.5);
    let mut s_rate = Stat::new("aim yaw change per decision beyond turn_rate*0.1 (rad)", 0.001);
    let mut worst: Vec<(f64, u64, String)> = vec![];
    let mut en_idle = 10.0;
    let mut pairs = 0;
    for k in 0..obs.len() - 1 {
        let (o0, o1) = (&obs[k], &obs[k + 1]);
        if o1.tick != o0.tick + 2 {
            continue;
        }
        let (a, b) = (&o0.me, &o1.me);
        let dyaw = wrap(b.aim[0] - a.aim[0]).abs();
        s_rate.add((dyaw - 0.4).max(0.0));
        let clamped_aim = dyaw >= 0.399;
        let _ = clamped_aim;
        // infer command
        let drain = a.energy - b.energy;
        let boost = drain > 0.3;
        let acc = if a.grounded { 58.5 } else { 12.0 } * 0.1;
        let dv = [b.vel[0] - a.vel[0], b.vel[1] - a.vel[1]];
        let n = hyp(dv[0], dv[1]);
        let top = if boost && a.grounded { 19.5 } else { 11.7 };
        let mv = if n < 2.0 * acc - 1e-3 { [b.vel[0] / top, b.vel[1] / top] } else { [dv[0] / n, dv[1] / n] };
        let jump = a.grounded && !b.grounded && b.vel[2] > 0.0;
        {
            let m = &mut sim.mechs[0];
            m.pos = a.pos;
            m.vel = a.vel;
            m.grounded = a.grounded;
            m.energy = a.energy;
            m.en_idle = en_idle;
            m.yaw = a.aim[0];
            m.pitch = a.aim[1];
            m.cmd = Cmd { mv, boost, aim: Some(b.aim), fire: [false, false], jump: false };
            m.jump_pending = jump;
        }
        sim.phys_mech(0);
        sim.phys_mech(0);
        let m = &sim.mechs[0];
        let perr = hyp(m.pos[0] - b.pos[0], m.pos[1] - b.pos[1]);
        s_pos.add(perr);
        s_posz.add(m.pos[2] - b.pos[2]);
        s_vel.add(hyp(m.vel[0] - b.vel[0], m.vel[1] - b.vel[1]));
        s_velz.add(m.vel[2] - b.vel[2]);
        s_en.add(m.energy - b.energy);
        s_gr.add(if m.grounded == b.grounded { 0.0 } else { 1.0 });
        pairs += 1;
        if drain > 0.3 {
            en_idle = 0.0;
        } else {
            en_idle += 0.1;
        }
        let e = perr + (m.pos[2] - b.pos[2]).abs();
        worst.push((e, o0.tick, format!("pos0={:?} vel0={:?} mv={:?} boost={} jump={} pred={:?}/{:?} obs={:?}/{:?} g {}->{}", a.pos, a.vel, mv, boost, jump, m.pos, m.vel, b.pos, b.vel, m.grounded, b.grounded)));
    }
    println!("## A. Self kinematics (replaying {} decision pairs through `phys_mech` x2 with the command inferred from the next observation)\n", pairs);
    println!("| quantity | n | mean abs err | max abs err | beyond tolerance | tol |\n|---|---|---|---|---|---|");
    for s in [&s_pos, &s_posz, &s_vel, &s_velz, &s_en, &s_gr, &s_rate] {
        println!("{}", s.line());
    }
    worst.sort_by(|a, b| b.0.partial_cmp(&a.0).unwrap());
    println!("\nWorst position mismatches:\n");
    for w in worst.iter().take(5) {
        println!("- tick {}: err {:.3} m — {}", w.1, w.0, w.2);
    }

    // ---------------------------------------------------------------- B. weapon timing
    println!("\n## B. Gun cooldown / reload timing\n");
    let mut cd_hist: HashMap<String, usize> = HashMap::new();
    let mut max_drop = 0.0f64;
    let mut reload_start: Option<f64> = None;
    let mut reload_durs = vec![];
    for k in 0..obs.len() - 1 {
        let (a, b) = (&obs[k], &obs[k + 1]);
        if b.tick != a.tick + 2 {
            continue;
        }
        if let (Some(Some(wa)), Some(Some(wb))) = (a.me.weapons.get(0), b.me.weapons.get(0)) {
            *cd_hist.entry(format!("{:.2}", wb.cooldown)).or_insert(0) += 1;
            max_drop = max_drop.max(wa.ammo.unwrap_or(0.0) - wb.ammo.unwrap_or(0.0));
            if wb.reload.unwrap_or(0.0) > 0.0 && wa.reload.unwrap_or(0.0) <= 0.0 {
                reload_start = Some(b.t - (2.4 - wb.reload.unwrap_or(0.0)));
            }
            if wb.reload.unwrap_or(0.0) <= 0.0 && wa.reload.unwrap_or(0.0) > 0.0 {
                if let Some(s) = reload_start.take() {
                    reload_durs.push(b.t - s);
                }
            }
        }
    }
    let mut keys: Vec<_> = cd_hist.iter().collect();
    keys.sort();
    println!("Observed gun `cooldown` values at decision time: {:?}", keys);
    println!("\nWith the model order (decrement timers, then fire) a trigger held from cooldown 0 shoots on the first tick of the window and the next decision shows 0.19 (0.24-0.05), then 0.09, then 0: matches the recording (a shot on tick A reads 0.19 after the second tick). Max ammo drop per decision: {} (<=1 expected).", max_drop);
    println!("Reload: measured start-to-refill durations {:?} (config reload 2.4 s; reload starts automatically when the magazine empties: observed `ammo 0, reload 2.35` on the decision after the last shot).", reload_durs.iter().map(|x| (x * 100.0).round() / 100.0).collect::<Vec<_>>());
    // model check
    {
        let m = &mut sim.mechs[0];
        m.slots = [Some(Weapon::new(crate::cfg::GUN, cfg)), None];
        m.cmd = Cmd { fire: [true, false], aim: None, ..Default::default() };
        m.grounded = true;
    }
    let mut seq = vec![];
    for _ in 0..8 {
        sim.weapons_tick(0);
        sim.weapons_tick(0);
        let w = sim.mechs[0].slots[0].as_ref().unwrap();
        seq.push((((w.cooldown.max(0.0)) * 100.0).round() / 100.0, w.ammo as i32));
    }
    println!("Model, trigger held 8 decisions (cooldown, ammo): {:?}", seq);

    // ---------------------------------------------------------------- C. projectiles
    println!("\n## C. Projectiles\n");
    let mut speeds: HashMap<String, (usize, f64, f64)> = HashMap::new();
    let mut s_pstep = Stat::new("gun bullet displacement vs vel*0.1 (m)", 0.01);
    let mut s_mstep = Stat::new("mortar/other displacement vs semi-implicit gravity (m)", 0.05);
    for k in 0..obs.len() - 1 {
        let (a, b) = (&obs[k], &obs[k + 1]);
        for p in &a.projectiles {
            let e = speeds.entry(p.kind.clone()).or_insert((0, f64::MAX, 0.0));
            let sp = dist3([0.0; 3], p.vel);
            e.0 += 1;
            e.1 = e.1.min(sp);
            e.2 = e.2.max(sp);
            if b.tick == a.tick + 2 {
                if let Some(q) = b.projectiles.iter().find(|q| q.id == p.id) {
                    if p.kind == "mortar" {
                        // two ticks: v1=v0-g dt, x+=v1 dt ; v2=v1-g dt, x+=v2 dt
                        let g = 22.0 * 0.05;
                        let v1 = [p.vel[0], p.vel[1], p.vel[2] - g];
                        let v2 = [p.vel[0], p.vel[1], p.vel[2] - 2.0 * g];
                        let pred = [p.pos[0] + (v1[0] + v2[0]) * 0.05, p.pos[1] + (v1[1] + v2[1]) * 0.05, p.pos[2] + (v1[2] + v2[2]) * 0.05];
                        s_mstep.add(dist3(pred, q.pos));
                    } else {
                        let pred = [p.pos[0] + p.vel[0] * 0.1, p.pos[1] + p.vel[1] * 0.1, p.pos[2] + p.vel[2] * 0.1];
                        s_pstep.add(dist3(pred, q.pos));
                    }
                }
            }
        }
    }
    println!("Projectile speed by kind (n, min, max): {:?}", speeds);
    println!("\n| quantity | n | mean abs err | max abs err | beyond tolerance | tol |\n|---|---|---|---|---|---|");
    println!("{}\n{}", s_pstep.line(), s_mstep.line());

    // ---------------------------------------------------------------- D. vision
    println!("\n## D. Vision membership\n");
    let mut seen_items: HashMap<i64, [f64; 3]> = HashMap::new();
    for o in &obs {
        for c in &o.crates {
            seen_items.insert(c.id, c.pos);
        }
        for c in &o.cubes {
            seen_items.insert(c.id, c.pos);
        }
        for c in &o.pickups {
            seen_items.insert(c.id, c.pos);
        }
    }
    let mut life: HashMap<i64, (u64, u64)> = HashMap::new();
    for o in &obs {
        for id in o.crates.iter().map(|c| c.id).chain(o.cubes.iter().map(|c| c.id)).chain(o.pickups.iter().map(|c| c.id)) {
            let e = life.entry(id).or_insert((o.tick, o.tick));
            e.1 = o.tick;
        }
    }
    let (mut tp, mut fnn, mut fp) = (0usize, 0usize, 0usize);
    let mut fn_list: Vec<String> = vec![];
    let mut fp_list: Vec<String> = vec![];
    let mut fp_by_id: HashMap<i64, usize> = HashMap::new();
    let mut mech_vis = 0usize;
    let mut mech_mem = 0usize;
    let mut mech_mem_viol = 0usize;
    let mut last_vis: HashMap<i64, f64> = HashMap::new();
    for o in &obs {
        let a = &o.me;
        let v = crate::obs::Viewer { eye: [a.pos[0], a.pos[1], a.pos[2] + 8.0], yaw: a.aim[0], near: 45.0, range: 200.0, half_fov: cfg.vis_fov * 0.5 };
        let listed: HashSet<i64> = o.crates.iter().map(|c| c.id).chain(o.cubes.iter().map(|c| c.id)).chain(o.pickups.iter().map(|c| c.id)).collect();
        for (id, p) in &seen_items {
            // an item only exists between its first and last listing (cubes/pickups spawn and vanish)
            let (f0, f1) = life[id];
            if o.tick < f0 || o.tick > f1 {
                continue;
            }
            let is_crate = *id >= 1000 && *id < 5000;
            let pred = if is_crate { sim.sees_body(&v, *p, 2.4) } else { sim.sees_point(&v, [p[0], p[1], p[2] + 0.5]) };
            let l = listed.contains(id);
            match (pred, l) {
                (true, true) => tp += 1,
                (false, true) => {
                    fnn += 1;
                    if fn_list.len() < 5 {
                        fn_list.push(format!("tick {} id {} listed but not predicted (dist {:.0} m, dyaw {:.0} deg)", o.tick, id, dist3(v.eye, *p), wrap((p[1] - v.eye[1]).atan2(p[0] - v.eye[0]) - v.yaw).to_degrees()));
                    }
                }
                (true, false) => {
                    fp += 1;
                    *fp_by_id.entry(*id).or_insert(0) += 1;
                    if fp_list.len() < 5 {
                        let tgt = [p[0], p[1], p[2] + 0.5];
                        fp_list.push(format!(
                            "tick {} id {} predicted but not listed (dist {:.0} m, dyaw {:.0} deg; eye {:?} -> {:?}; prism hit {:?}, terrain hit {:?})",
                            o.tick,
                            id,
                            dist3(v.eye, *p),
                            wrap((p[1] - v.eye[1]).atan2(p[0] - v.eye[0]) - v.yaw).to_degrees(),
                            v.eye,
                            tgt,
                            world.ray_prisms(v.eye, tgt),
                            world.ray_terrain(v.eye, tgt)
                        ));
                    }
                }
                _ => {}
            }
        }
        for m in &o.mechs {
            let pred = sim.sees_body(&v, m.pos, 9.0);
            if pred {
                mech_vis += 1;
                last_vis.insert(m.id, o.t);
            } else {
                mech_mem += 1;
                if last_vis.get(&m.id).map_or(true, |t| o.t - *t > 5.0 + 1e-6) {
                    mech_mem_viol += 1;
                }
            }
        }
    }
    println!("Static items (crates, cubes, pickups; {} distinct ids ever listed), per observation: listed&predicted {}, listed-but-not-predicted {}, predicted-but-not-listed {}.", seen_items.len(), tp, fnn, fp);
    for l in fn_list.iter().chain(fp_list.iter()) {
        println!("- {}", l);
    }
    println!("Predicted-but-not-listed counts by item id: {:?}", fp_by_id);
    println!("\nMechs in the list: {} predicted visible now, {} not visible now (memory); of the latter {} had no predicted sighting within 5 s (memory violations; includes sightings before the recording window).", mech_vis, mech_mem, mech_mem_viol);

    // ---------------------------------------------------------------- E. sounds
    println!("\n## E. Sounds\n");
    let mut errs = vec![];
    let mut cls: HashMap<(String, String), usize> = HashMap::new();
    let mut ages: HashMap<String, usize> = HashMap::new();
    let mut cls_bad = 0;
    let mut cls_n = 0;
    for o in &obs {
        let vis: Vec<&Actor> = o.mechs.iter().filter(|m| m.kind == "mech").collect();
        for s in &o.sounds {
            *cls.entry((s.kind.clone(), s.dist.clone())).or_insert(0) += 1;
            *ages.entry(format!("{:.2}", s.age)).or_insert(0) += 1;
            let lb: Vec<&Beam> = o.beams.iter().filter(|b| b.kind == "laser").collect();
            if vis.len() <= 1 && s.kind == "laser" && lb.len() == 1 {
                let m = Actor { pos: lb[0].path[0], ..Default::default() };
                let truth = (m.pos[1] - o.me.pos[1]).atan2(m.pos[0] - o.me.pos[0]);
                errs.push(wrap(s.bearing - truth).to_degrees());
                let d = dist3(o.me.pos, m.pos);
                let c = if d < 60.0 { "near" } else if d < 160.0 { "mid" } else { "far" };
                cls_n += 1;
                if c != s.dist {
                    cls_bad += 1;
                }
            }
        }
    }
    let n = errs.len() as f64;
    let mean = errs.iter().sum::<f64>() / n.max(1.0);
    let sd = (errs.iter().map(|e| (e - mean).powi(2)).sum::<f64>() / n.max(1.0)).sqrt();
    println!("Sound kinds/dist classes seen: {:?}", cls);
    println!("Sound ages seen: {:?}", ages);
    println!("Bearing error vs the (only) visible mech, n={}: mean {:.1} deg, sd {:.1} deg (configured sigma {} deg; sample is contaminated by other sources/NPCs).", errs.len(), mean, sd, cfg.bearing_noise.to_degrees());
    println!("Distance-class agreement with that mech: {}/{} mismatches.", cls_bad, cls_n);

    // ---------------------------------------------------------------- F. damage / events
    println!("\n## F. Damage events\n");
    let mut amounts: HashMap<String, usize> = HashMap::new();
    let (mut rear_ok, mut rear_n) = (0, 0);
    let mut hp_series_ok = 0;
    let mut hp_series_n = 0;
    let mut last_dmg_t = -100.0;
    for k in 0..obs.len() {
        let o = &obs[k];
        let mut dmg_now = false;
        for e in &o.events {
            if e.t == "damaged" {
                dmg_now = true;
                *amounts.entry(format!("{} {} rear={}", e.weapon.clone().unwrap_or_default(), e.amount.unwrap_or(0.0), e.rear.unwrap_or(false))).or_insert(0) += 1;
                if let Some(bg) = e.bearing {
                    let rear = wrap(bg - o.me.aim[0]).abs() > std::f64::consts::FRAC_PI_2;
                    rear_n += 1;
                    if rear == e.rear.unwrap_or(false) {
                        rear_ok += 1;
                    }
                }
            }
            if e.t == "hit" {
                dmg_now = true;
            }
        }
        if k > 0 && obs[k].tick == obs[k - 1].tick + 2 && !dmg_now && !o.me.weapons.is_empty() {
            let d = o.me.hp - obs[k - 1].me.hp;
            let since = obs[k - 1].t - last_dmg_t;
            hp_series_n += 1;
            let expect = if since >= 5.0 && o.me.in_zone { 4.5f64.min(o.me.max_hp - obs[k - 1].me.hp) } else { 0.0 };
            if (d - expect).abs() < 2.3 {
                hp_series_ok += 1;
            }
        }
        if dmg_now {
            last_dmg_t = o.t;
        }
    }
    println!("Damage event amounts: {:?}", amounts);
    println!("Rear flag vs geometric rule (|bearing-aim_yaw| > 90 deg): {}/{} agree.", rear_ok, rear_n);
    println!("HP regen (45/s after 5 s without dealing/taking damage; tolerance 2.3 hp per decision since damage timing within the window is unknown): {}/{} decision pairs consistent.", hp_series_ok, hp_series_n);

    // ---------------------------------------------------------------- G. config parity
    println!("\n## G. Config parity\n");
    let o0 = &obs[0];
    let mut diff = vec![];
    for (k, v) in &o0.me.stats {
        let c = cfg.mech.get(k).copied();
        if c.map_or(true, |c| (c - v).abs() > 1e-9) {
            diff.push(format!("{k}: obs {v} vs cfg {c:?}"));
        }
    }
    println!("`self.stats` keys differing from hello `mech` config: {:?}", diff);
    let z = &o0.zone;
    let (c, r, nc, nr, s, e, dps) = sim.zone_at(0.0);
    println!("Zone at t=0: obs radius {} next_radius {} shrink {}..{} dps {}; sim radius {} next_radius {} shrink {}..{} dps {} (centers are random per match: obs next_center {:?}, sim {:?}; initial center obs {:?} sim {:?}).", z.radius, z.next_radius, z.shrink_start, z.shrink_end, z.dps, r, nr, s, e, dps, z.next_center, nc, z.center, c);
}
